const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'../..');
const normalized=text=>text.replace(/\r\n/g,'\n');
const base=normalized(fs.readFileSync(path.join(root,'prototype/teaching-prompt.txt'),'utf8')).trim();
const opening=normalized(fs.readFileSync(path.join(root,'prototype/teaching-opening.txt'),'utf8')).trim();
const contract=normalized(fs.readFileSync(path.join(root,'prototype/teaching-contract.txt'),'utf8')).trim();
const {requestOptions:options,retryInstruction,outputInstruction}=require('../teaching-instructions.cjs');
const output='// Generated by prototype/prompt-lab/sync-prompt.cjs. Edit the canonical prompt files.\n'
 +'enum TeachingInstructions {\n    static let base = #"""\n'+base+'\n"""#\n'
 +'    static let opening = #"""\n'+opening+'\n"""#\n'
 +'    static let contract = #"""\n'+contract+'\n"""#\n'
 +'    static let retry = '+JSON.stringify(retryInstruction)+'\n'
 +'    static let outputInstruction = '+JSON.stringify(outputInstruction)+'\n'
 +'    static let model = '+JSON.stringify(options.model)+'\n'
 +'    static let maxTokens = '+options.max_tokens+'\n'
 +'    static let thinkingType = '+JSON.stringify(options.thinking.type)+'\n'
 +'    static let reasoningEffort = '+JSON.stringify(options.reasoning_effort)+'\n'
 +'    static let responseFormatType = '+JSON.stringify(options.response_format.type)+'\n}\n';
const target=path.join(root,'ios/StudentHelper/TeachingInstructions.swift');
if(process.argv.includes('--check')) { if(normalized(fs.readFileSync(target,'utf8'))!==output)throw Error('Web and native teaching prompts differ');console.log('PASS: web and iOS prompts match'); }
else fs.writeFileSync(target,output);
